#!/usr/bin/env node
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const sdkIndex = path.join(root, 'test/contract/cursor-sdk/index.d.ts');
const outFile = path.join(root, 'test/contract/consumer.ts');

if (!fs.existsSync(sdkIndex)) {
  console.error('Run pnpm run sync:sdk first');
  process.exit(1);
}

const raw = fs.readFileSync(sdkIndex, 'utf8');
const values = [];
const types = [];

function stripComments(text) {
  return text.replace(/\/\*[\s\S]*?\*\//g, '').replace(/\/\/.*$/gm, '');
}

const cleaned = stripComments(raw);

for (const match of cleaned.matchAll(
  /export\s+type\s+\{([^}]+)\}\s+from\s+["'][^"']+["']/g,
)) {
  for (const part of match[1].split(',')) {
    const name = part.trim().split(/\s+/).pop();
    if (name) {
      types.push(name);
    }
  }
}

for (const match of cleaned.matchAll(
  /export\s+\{([^}]+)\}\s+from\s+["'][^"']+["']/g,
)) {
  for (const part of match[1].split(',')) {
    const bits = part.trim().split(/\s+as\s+/);
    const name = bits[bits.length - 1].trim();
    if (name) {
      values.push(name);
    }
  }
}

const uniqueValues = [...new Set(values)].sort();
const uniqueTypes = [...new Set(types)].sort();

const body = `/**
 * Generated by scripts/generate-contract-consumer.mjs — do not edit.
 */
import {
${uniqueValues.map((n) => `  ${n},`).join('\n')}
} from 'cursor/canvas';

import type {
${uniqueTypes.map((n) => `  ${n},`).join('\n')}
} from 'cursor/canvas';

const _values = {
${uniqueValues.map((n) => `  ${n},`).join('\n')}
};

type _Types = [
${uniqueTypes
  .filter((n) => n !== 'RefObject' && n !== 'SetCanvasState')
  .map((n) => `  ${n},`)
  .join('\n')}
];
type _RefObject = RefObject<HTMLDivElement>;
type _SetCanvasState = SetCanvasState<number>;

const theme = useHostTheme();
const _themeProbe: unknown = [
  theme.category.orange,
  theme.tokens.category.orange,
  theme.fill.secondary,
  theme.chart.palette.lightGreen,
  theme.chart.sequence[0],
];

export {};
`;

fs.mkdirSync(path.dirname(outFile), { recursive: true });
fs.writeFileSync(outFile, body);
console.log(
  `Wrote ${outFile} (${uniqueValues.length} values, ${uniqueTypes.length} types)`,
);
